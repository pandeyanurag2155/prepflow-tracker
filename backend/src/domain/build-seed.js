import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { LEVELS } from './constants.js';
import { SYSDESIGN_SEED } from './sysdesign-seed.js';
import { TOOLS_SEED } from './tools-seed.js';
import { CORE_SEED } from './core-seed.js';
import { keyFor } from './problem-key.js';
import {
  TAG_TRACK, ROADMAP_SEED, PRACTISE_TIPS, DIFF_CODE, DSA_SEED, STRIVER_WRAP_UP, REVISION_SEED, REVISION_EXTRA,
} from './seed-data.js';

const STRIVER_SHEET = JSON.parse(readFileSync(new URL('./striver-sheet.json', import.meta.url), 'utf8'));
// NeetCode title → { link, source, premium }, generated by scripts/fetch-dsa-links.js
const DSA_LINKS = JSON.parse(readFileSync(new URL('./dsa-links.json', import.meta.url), 'utf8'));

const cap = s => (s ? s[0].toUpperCase() + s.slice(1) : s);
const splitList = (v, sep = '; ') => (Array.isArray(v) ? v : String(v || '').split(sep).map(s => s.trim()).filter(Boolean));

/** Collects groups/items (API shape, camelCase) with per-parent order counters. Groups come out parents-first. */
function createBuilder() {
  const groups = [];
  const items = [];
  const counters = new Map();
  const next = k => { const n = counters.get(k) || 0; counters.set(k, n + 1); return n; };

  const group = (sectionId, f) => {
    const g = {
      id: randomUUID(), sectionId, parentId: f.parentId || null, title: f.title || '',
      month: f.month ?? null, focus: f.focus || '', step: f.step ?? null, role: f.role || null,
      order: next(`g:${sectionId}:${f.parentId || ''}`),
    };
    groups.push(g);
    return g;
  };
  const item = (g, f) => {
    items.push({
      id: randomUUID(), sectionId: g.sectionId, groupId: g.id, title: f.title, kind: f.kind,
      track: f.track || '', level: f.level || '', difficulty: f.difficulty || '', notes: f.notes || '', link: f.link || '',
      done: false, doneAt: null, revisitDates: [], key: keyFor(f.kind, f.title), order: next(`i:${g.id}`),
    });
  };
  return { groups, items, group, item };
}

/** Link (and a Premium note) for a NeetCode problem; empty if dsa-links.json doesn’t know it. */
export function dsaLinkFields(title) {
  const l = DSA_LINKS[title];
  return l ? { link: l.link, notes: l.premium ? 'LeetCode Premium problem' : '' } : {};
}

/** LeetCode is the practice link when the sheet has one; takeUforward’s page otherwise. Extras go in notes. */
function striverItemFields(p) {
  const link = p.leetcode || p.tuf;
  const notes = [
    p.premium && 'LeetCode Premium problem',
    p.leetcode && `takeUforward: ${p.tuf}`,
    p.article && `Article: ${p.article}`,
    p.video && `Video: ${p.video}`,
  ].filter(Boolean).join('\n');
  return { kind: p.kind, title: p.title, difficulty: p.kind === 'problem' ? p.difficulty : '', link, notes };
}

/**
 * Striver section from striver-sheet.json: self-paced, so no schedule. One step per sheet chapter
 * (numbered in the sheet’s order) with its sub-categories, then a wrap-up step of our own.
 */
function addStriver({ group, item }) {
  STRIVER_SHEET.chapters.forEach((chapter, i) => {
    const step = group('striver', { step: i + 1, title: chapter.title });
    for (const sub of chapter.subs) {
      const g = group('striver', { title: sub.title, parentId: step.id });
      sub.items.forEach(p => item(g, striverItemFields(p)));
    }
  });
  const [title, subs] = STRIVER_WRAP_UP;
  const wrapUp = group('striver', { title });
  subs.forEach(t => group('striver', { title: t, parentId: wrapUp.id }));
}

/** Only the Striver section (used to refresh it in an existing database). */
export function buildStriverSeed() {
  const b = createBuilder();
  addStriver(b);
  return { groups: b.groups, items: b.items };
}

/** The whole starting plan. */
export function buildSeed() {
  const b = createBuilder();
  const { group, item } = b;

  for (const [month, title, focus, tasks] of ROADMAP_SEED) {
    const g = group('roadmap', { month, title, focus });
    for (const t of tasks) {
      // A trailing [DSA]/[SD]/[Deep]/[Beh]/[App] sets the track; “Checkpoint: …” tasks get the Checkpoint track.
      const m = t.match(/\s*\[(DSA|SD|Deep|Beh|App)\]$/);
      item(g, {
        kind: 'task',
        title: m ? t.slice(0, m.index) : t,
        track: m ? TAG_TRACK[m[1]] : (/^Checkpoint:/.test(t) ? 'Checkpoint' : ''),
      });
    }
  }

  const tips = group('dsa', { title: 'How to practise', role: 'tips' });
  PRACTISE_TIPS.forEach(t => item(tips, { kind: 'concept', title: t }));
  for (const [month, title, concepts, problems] of DSA_SEED) {
    const g = group('dsa', { month, title });
    splitList(concepts).forEach(t => item(g, { kind: 'concept', title: cap(t) }));
    splitList(problems, ', ').forEach(p => {
      const m = p.match(/^(.*\S)\s+([EMH])$/);
      const title = m ? m[1] : p;
      item(g, { kind: 'problem', title, difficulty: m ? DIFF_CODE[m[2]] : '', ...dsaLinkFields(title) });
    });
  }

  addStriver(b);

  for (const [lang, levels] of Object.entries(REVISION_SEED)) {
    const g = group('revision', { title: lang });
    levels.forEach((str, i) => splitList(str).forEach(t => item(g, { kind: 'topic', title: t, level: LEVELS[i] })));
    (REVISION_EXTRA[lang] || []).forEach(([level, title, link]) => item(g, { kind: 'topic', title, level, link }));
  }

  // Levelled reading lists: one group per track/tool, topics tagged Basic / Intermediate / Advanced
  for (const [sectionId, seed] of [['sysdesign', SYSDESIGN_SEED], ['tools', TOOLS_SEED]]) {
    for (const [track, topics] of Object.entries(seed)) {
      const g = group(sectionId, { title: track });
      topics.forEach(([level, title, link]) => item(g, { kind: 'topic', title, level, link }));
    }
  }

  // Core subjects: subject → chapter → topics (no levels)
  for (const [subject, chapters] of Object.entries(CORE_SEED)) {
    const s = group('core', { title: subject });
    for (const [chapter, topics] of chapters) {
      const c = group('core', { title: chapter, parentId: s.id });
      topics.forEach(([title, link]) => item(c, { kind: 'topic', title, link }));
    }
  }

  return { groups: b.groups, items: b.items };
}

/** Seed records of one section only (used to add a new section to an existing database). */
export function buildSectionSeed(sectionId) {
  const { groups, items } = buildSeed();
  return { groups: groups.filter(g => g.sectionId === sectionId), items: items.filter(i => i.sectionId === sectionId) };
}
